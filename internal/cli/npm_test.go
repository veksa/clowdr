func TestLockfiles(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "yarn.lock"), []byte(berryLock), 0o644)
	os.WriteFile(filepath.Join(dir, "package-lock.json"), []byte(`{"lockfileVersion": 3, "packages": {
		"": {"name": "app"},
		"node_modules/@acme/other": {"version": "2.0.0", "resolved": "https://deploy.example.com/npm/@acme/other/-/other-2.0.0.tgz"},
		"node_modules/@acme/tool": {"version": "1.1.0"},
		"node_modules/a/node_modules/@acme/tool": {"version": "1.0.0"},
		"node_modules/local": {"version": "1.0.0", "resolved": "file:../local"},
		"packages/x": {"version": "1.0.0"},
		"node_modules/linked": {"link": true}}}`), 0o644)
	ps, err := lockedPackages(dir)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, p := range ps {
		got = append(got, p.Name+"@"+p.Version)
	}
	want := "@acme/other@2.0.0 @acme/tool@1.0.0 @acme/tool@1.1.0 left-pad@1.3.0 string-width@4.2.3"
	if strings.Join(got, " ") != want {
		t.Fatalf("got  %s\nwant %s", strings.Join(got, " "), want)
	}
	v1 := filepath.Join(t.TempDir(), "package-lock.json")
	os.WriteFile(v1, []byte(`{"lockfileVersion": 1, "dependencies": {"@acme/tool": {"version": "1.0.0", "dependencies": {"@acme/dep": {"version": "3.0.0"}}}, "x": {"version": "file:../x"}}}`), 0o644)
	ps, _ = parsePackageLock(v1)
	if len(ps) != 2 {
		t.Fatalf("v1: %+v", ps)
	}
}

// tgzOf packs package.json content as an npm tarball.
func tgzOf(t *testing.T, packageJSON string) []byte {
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	tw.WriteHeader(&tar.Header{Name: "package/package.json", Mode: 0o644, Size: int64(len(packageJSON)), Typeflag: tar.TypeReg})
	tw.Write([]byte(packageJSON))
	tw.Close()
	gz.Close()
	return buf.Bytes()
}

func TestBuildPublishBody(t *testing.T) {
	reg := "https://deploy.example.com/npm/"
	tgz := tgzOf(t, `{"name":"@acme/tool","version":"1.2.3","description":"d","dependencies":{"x":"^1"}}`)
	body, name, version, err := buildPublishBody(reg, tgz, "beta")
	if err != nil || name != "@acme/tool" || version != "1.2.3" {
		t.Fatal(name, version, err)
	}
	var doc struct {
		Name     string            `json:"name"`
		DistTags map[string]string `json:"dist-tags"`
		Versions map[string]struct {
			Name, Version, ID string
			Dependencies      map[string]string `json:"dependencies"`
			Dist              struct{ Integrity, Shasum, Tarball string }
		} `json:"versions"`
		Attachments map[string]struct {
			Data   string `json:"data"`
			Length int    `json:"length"`
		} `json:"_attachments"`
	}
	if err := json.Unmarshal(body, &doc); err != nil {
		t.Fatal(err)
	}
	s512, s1 := sha512.Sum512(tgz), sha1.Sum(tgz)
	v := doc.Versions["1.2.3"]
	if doc.Name != "@acme/tool" || doc.DistTags["beta"] != "1.2.3" || v.Name != "@acme/tool" || v.Dependencies["x"] != "^1" {
		t.Fatalf("%s", body)
	}
	if v.Dist.Integrity != "sha512-"+base64.StdEncoding.EncodeToString(s512[:]) || v.Dist.Shasum != hex.EncodeToString(s1[:]) ||
		v.Dist.Tarball != reg+"@acme/tool/-/tool-1.2.3.tgz" {
		t.Fatalf("dist: %+v", v.Dist)
	}
	att := doc.Attachments["@acme/tool-1.2.3.tgz"]
	if data, _ := base64.StdEncoding.DecodeString(att.Data); !bytes.Equal(data, tgz) || att.Length != len(tgz) {
		t.Fatal("attachment")
	}
	if _, _, _, err := buildPublishBody(reg, tgzOf(t, `{"name":"tool","version":"1.0.0"}`), ""); err == nil {
		t.Fatal("unscoped name accepted")
	}
}

func TestNPMExpiryWarning(t *testing.T) {
	now := time.Date(2026, 11, 14, 0, 0, 0, 0, time.UTC)
	var errb bytes.Buffer
	a := &app{err: &errb, cfg: &UserConfig{NPM: &NPMConfig{Logins: []*NPMLogin{
		{Registry: "https://a.example/npm/", Name: "soon", Expires: now.Add(10 * 24 * time.Hour)},
		{Registry: "https://b.example/npm/", Name: "later", Expires: now.Add(60 * 24 * time.Hour)},
		{Registry: "https://c.example/npm/", Name: "gone", Expires: now.Add(-time.Hour)},
	}}}}
	a.warnNPMExpiry(now)
	got := errb.String()
	contains(t, got, "npm token soon for https://a.example/npm/ expires in 10 days (2026-11-24)", "clowctl npm token rotate soon",
		"npm token gone for https://c.example/npm/ has expired")
	if strings.Contains(got, "later") {
		t.Fatalf("warned about a token with 60 days left:\n%s", got)
	}
}

// Against a server without the npm feature every npm command says so instead of failing oddly.
func TestNPMOldServer(t *testing.T) {
	old := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/v1/version" {
			json.NewEncoder(w).Encode(api.Version{Version: "v0.3.1", Registry: "fs"})
			return
		}
		http.NotFound(w, r)
	}))
	defer old.Close()
	dir := t.TempDir()
	t.Setenv("HOME", dir)
	t.Setenv("CLOWDR_CONFIG", filepath.Join(dir, "config"))
	t.Setenv("CLOWDR_TOKEN", "")
	wd, _ := os.Getwd()
	t.Cleanup(func() { os.Chdir(wd) })
	os.Chdir(dir)
	h := &harness{t: t, dir: dir}
	cfg := &UserConfig{path: filepath.Join(dir, "config"), Current: "old", Contexts: map[string]*Context{"old": {Server: old.URL, Token: "clw_x_y"}},
		NPM: &NPMConfig{Logins: []*NPMLogin{{Registry: registryURL(old.URL), Name: "m", Token: "clwn_a_b", Expires: time.Now().Add(time.Hour)}}}}
	if err := cfg.Save(); err != nil {
		t.Fatal(err)
	}
	for _, args := range [][]string{
		{"npm", "login", "--scope", "@acme"}, {"npm", "token", "ls"}, {"npm", "token", "revoke", "m"}, {"npm", "audit"},
		{"npm", "token", "rotate"}, {"npm", "token", "rotate", "m"},
	} {
		contains(t, h.fails(args...), "server too old for npm (needs clowdrd "+npmMinServer)
	}
	os.WriteFile(filepath.Join(dir, "package.json"), []byte(`{"name":"@acme/tool","version":"1.0.0","publishConfig":{"registry":"`+registryURL(old.URL)+`"}}`), 0o644)
	contains(t, h.fails("npm", "publish"), "server too old for npm")
}

// The dependency-confusion guard needs no registry: an unmapped private scope fails before any
// request.
func TestNPMCheckConfusionGuard(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("HOME", filepath.Join(dir, "home"))
	reg := "https://deploy.example.com/npm/"
	a := &app{cfg: &UserConfig{Contexts: map[string]*Context{}, NPM: &NPMConfig{Logins: []*NPMLogin{{Registry: reg, Name: "m", Token: "t", Scopes: []string{"@acme"}}}}}}
	os.WriteFile(filepath.Join(dir, "package.json"), []byte(`{"dependencies":{"@acme/tool":"^1.0.0","left-pad":"^1"}}`), 0o644)

	res, err := a.npmCheck(context.Background(), dir)
	if err != nil || !res.Guarded || len(res.Problems) != 1 || !strings.Contains(res.Problems[0].Message, "clowctl npm setup --scope @acme") {
		t.Fatalf("%+v %v", res, err)
	}
	// Mapped to a registry that is not clowdr's.
	os.WriteFile(filepath.Join(dir, ".yarnrc.yml"), []byte("npmScopes:\n  acme:\n    npmRegistryServer: https://evil.example/\n"), 0o644)
	res, _ = a.npmCheck(context.Background(), dir)
	if len(res.Problems) != 1 || !strings.Contains(res.Problems[0].Message, "not a clowdr registry") {
		t.Fatalf("%+v", res)
	}
	// Mapped through .npmrc for an npm project.
	os.Remove(filepath.Join(dir, ".yarnrc.yml"))
	os.WriteFile(filepath.Join(dir, ".npmrc"), []byte("@acme:registry="+reg+"\n"), 0o644)
	if res, err := a.npmCheck(context.Background(), dir); err != nil || len(res.Problems) != 0 {
		t.Fatalf("%+v %v", res, err)
	}
	// A scope mapped to clowdr in the project is guarded even without a login for it.
	b := &app{cfg: &UserConfig{Contexts: map[string]*Context{"c": {Server: "https://deploy.example.com"}}}}
	os.WriteFile(filepath.Join(dir, ".npmrc"), []byte("@acme:registry="+reg+"\n"), 0o644)
	os.WriteFile(filepath.Join(dir, "package.json"), []byte(`{"dependencies":{"@zzz/x":"1"}}`), 0o644)
	if res, _ := b.npmCheck(context.Background(), dir); res.Guarded {
		t.Fatalf("an unrelated scope was guarded: %+v", res)
	}
	// No private scope at all: nothing to check.
	c := &app{cfg: &UserConfig{Contexts: map[string]*Context{}}}
	if res, _ := c.npmCheck(context.Background(), dir); res.Guarded {
		t.Fatal("guarded without any private scope")
	}
}

// TestNPMWorkflow runs the commands against the real API: login, setup, publish, check (fine,
// then deprecated, then unmapped), deploy with and without --allow-outdated, rotation, audit and
// revocation. npm and yarn are not needed: packing is replaced by a tarball of package.json.
func TestNPMWorkflow(t *testing.T) {
	h := newHarness(t)
	old := packTarball
	packTarball = func(_ context.Context, dir string) ([]byte, error) {
		b, err := os.ReadFile(filepath.Join(dir, "package.json"))
		if err != nil {
			return nil, err
		}
		return tgzOf(t, string(b)), nil
	}
	t.Cleanup(func() { packTarball = old })
	home := os.Getenv("HOME")
	reg := registryURL(h.srv.URL)

	out := h.ok("npm", "login", "--context", "test", "--name", "laptop", "--scope", "@acme", "--scope", "npm:publish:@acme/*")
	contains(t, out, "logged in to "+reg+" as laptop")
	cfg, _ := loadUserConfig()
	l := cfg.npmLogin(reg)
	if l == nil || l.Name != "laptop" || !strings.HasPrefix(l.Token, "clwn_") || len(l.Scopes) != 1 || l.Scopes[0] != "@acme" {
		t.Fatalf("config: %+v", l)
	}
	if v, _ := yamlGet(filepath.Join(home, ".yarnrc.yml"), "npmRegistries", reg, "npmAuthToken"); v != l.Token {
		t.Fatal("~/.yarnrc.yml has no token")
	}
	if npmrcGet(filepath.Join(home, ".npmrc"), npmrcAuthKey(reg)) != l.Token {
		t.Fatal("~/.npmrc has no token")
	}
	for _, f := range []string{".yarnrc.yml", ".npmrc"} {
		if fi, _ := os.Stat(filepath.Join(home, f)); fi.Mode().Perm() != 0o600 {
			t.Fatalf("%s mode %v", f, fi.Mode().Perm())
		}
	}
	contains(t, h.ok("npm", "login", "--context", "test", "--name", "laptop"), "already logged in")

	// A package to publish.
	pkg := filepath.Join(h.dir, "pkg")
	os.MkdirAll(pkg, 0o755)
	writePkg := func(version string) {
		os.WriteFile(filepath.Join(pkg, "package.json"), []byte(`{"name":"@acme/tool","version":"`+version+`","publishConfig":{"registry":"`+reg+`"}}`), 0o644)
	}
	writePkg("1.0.0")
	contains(t, h.ok("npm", "publish", "pkg", "--context", "test"), "published @acme/tool@1.0.0 (latest)")
	contains(t, h.fails("npm", "publish", "pkg", "--context", "test"), "already published")
	os.WriteFile(filepath.Join(pkg, "package.json"), []byte(`{"name":"@acme/tool","version":"1.0.1","publishConfig":{"registry":"https://elsewhere.example/npm/"}}`), 0o644)
	contains(t, h.fails("npm", "publish", "pkg"), "not a clowdr registry")
	os.WriteFile(filepath.Join(pkg, "package.json"), []byte(`{"name":"tool","version":"1.0.1","publishConfig":{"registry":"`+reg+`"}}`), 0o644)
	contains(t, h.fails("npm", "publish", "pkg"), "only scoped names")

	// The deploy project uses the package.
	os.WriteFile(filepath.Join(h.dir, "package.json"), []byte(`{"name":"shop","dependencies":{"@acme/tool":"^1.0.0"}}`), 0o644)
	os.WriteFile(filepath.Join(h.dir, "yarn.lock"), []byte(`__metadata:
  version: 8

"@acme/tool@npm:^1.0.0":
  version: 1.0.0
  resolution: "@acme/tool@npm:1.0.0"
  languageName: node
  linkType: hard
`), 0o644)
	contains(t, h.fails("npm", "check"), "1 problem(s)")
	_, errOut, _ := h.run("npm", "check")
	contains(t, errOut, "does not map it", "clowctl npm setup --scope @acme")
	contains(t, h.ok("npm", "setup", "--scope", "@acme", "--context", "test"), "@acme → "+reg)
	if v, _ := yamlGet(filepath.Join(h.dir, ".yarnrc.yml"), "npmScopes", "acme", "npmRegistryServer"); v != reg {
		t.Fatalf("project .yarnrc.yml: %q", v)
	}
	contains(t, h.ok("npm", "check"), "are current")

	// Three newer versions: retention deprecates the locked 1.0.0.
	for _, v := range []string{"1.1.0", "1.2.0", "1.3.0"} {
		writePkg(v)
		h.ok("npm", "publish", "pkg", "--context", "test", "--tag", "latest")
	}
	contains(t, h.fails("npm", "check"), "problem(s)")
	_, errOut, _ = h.run("npm", "check")
	contains(t, errOut, "@acme/tool@1.0.0 is deprecated (removed on", "upgrade to 1.3.0", "yarn up @acme/tool")

	// deploy runs the check; --allow-outdated deploys and is recorded.
	h.srv.Project(t, "shop", "shop.example.com")
	contains(t, h.fails("deploy", "web"), "--allow-outdated")
	h.ok("deploy", "web", "--allow-outdated")
	contains(t, h.ok("releases", "web"), "(allow-outdated)")
	os.WriteFile(filepath.Join(h.dir, "yarn.lock"), []byte("\"@acme/tool@npm:^1.3.0\":\n  version: 1.3.0\n  resolution: \"@acme/tool@npm:1.3.0\"\n"), 0o644)
	h.ok("deploy", "web")
	if out := h.ok("releases", "web"); strings.Count(out, "(allow-outdated)") != 1 {
		t.Fatalf("only the first deploy skipped the check:\n%s", out)
	}

	// Tokens: list, self-rotation (the old token works 24 h more), admin rotation --now, revoke.
	contains(t, h.ok("npm", "token", "ls", "--context", "test"), "laptop", "npm:read:@acme/*", "active")
	first := l.Token
	contains(t, h.ok("npm", "token", "rotate", "--context", "test"), "rotated (the old one works 24 h more)")
	cfg, _ = loadUserConfig()
	second := cfg.npmLogin(reg).Token
	if second == first || npmrcGet(filepath.Join(home, ".npmrc"), npmrcAuthKey(reg)) != second {
		t.Fatal("self-rotation did not rewrite the files")
	}
	if v, _ := yamlGet(filepath.Join(home, ".yarnrc.yml"), "npmRegistries", reg, "npmAuthToken"); v != second {
		t.Fatal("self-rotation did not rewrite ~/.yarnrc.yml")
	}
	contains(t, h.ok("npm", "token", "ls", "--context", "test"), "rotated, works until")
	contains(t, h.ok("npm", "token", "rotate", "laptop", "--now", "--context", "test"), "the old one stopped")
	cfg, _ = loadUserConfig()
	if cfg.npmLogin(reg).Token == second {
		t.Fatal("admin rotation did not rewrite the local token")
	}
	contains(t, h.ok("npm", "check"), "are current")

	contains(t, h.ok("npm", "audit", "--context", "test", "--package", "@acme/tool", "--limit", "50"), "publish", "laptop", "@acme/tool", "1.3.0")
	contains(t, h.ok("npm", "audit", "--context", "test", "--action", "token"), "token.rotate", "token.create")

	h.ok("npm", "token", "revoke", "laptop", "--context", "test")
	contains(t, h.fails("npm", "check"), "not accepted (expired or revoked)")
	contains(t, h.fails("npm", "token", "revoke", "laptop", "--context", "test"), "not found")
}
