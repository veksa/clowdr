func TestYarnrcEditing(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, ".yarnrc.yml")
	orig := `# my yarn settings
nodeLinker: node-modules # keep me
npmRegistries:
  "https://other.example/":
    npmAuthToken: other-token
enableTelemetry: false
`
	os.WriteFile(p, []byte(orig), 0o644)
	reg := "https://deploy.example.com/npm/"
	for i := 0; i < 2; i++ { // the second run replaces, never duplicates
		if err := yamlSet(p, "clwn_secret_"+string(rune('a'+i)), true, "npmRegistries", reg, "npmAuthToken"); err != nil {
			t.Fatal(err)
		}
	}
	b, _ := os.ReadFile(p)
	got := string(b)
	for _, want := range []string{"# my yarn settings", "# keep me", "nodeLinker: node-modules", "enableTelemetry: false", "other-token"} {
		if !strings.Contains(got, want) {
			t.Errorf("lost %q:\n%s", want, got)
		}
	}
	if strings.Count(got, reg) != 1 || strings.Contains(got, "clwn_secret_a") {
		t.Fatalf("token not replaced in place:\n%s", got)
	}
	if v, _ := yamlGet(p, "npmRegistries", reg, "npmAuthToken"); v != "clwn_secret_b" {
		t.Fatalf("read back %q", v)
	}
	if v, _ := yamlGet(p, "npmRegistries", "https://other.example/", "npmAuthToken"); v != "other-token" {
		t.Fatalf("other registry: %q", v)
	}
	checkMode(t, p, 0o600)

	// A project file keeps its mode; a new file is created with the mappings.
	proj := filepath.Join(dir, "proj.yml")
	os.WriteFile(proj, []byte("yarnPath: .yarn/releases/yarn.cjs\n"), 0o644)
	if err := yamlSet(proj, reg, false, "npmScopes", "acme", "npmRegistryServer"); err != nil {
		t.Fatal(err)
	}
	checkMode(t, proj, 0o644)
	fresh := filepath.Join(dir, "sub", "new.yml")
	if err := yamlSet(fresh, reg, false, "npmScopes", "acme", "npmRegistryServer"); err != nil {
		t.Fatal(err)
	}
	if v, _ := yamlGet(fresh, "npmScopes", "acme", "npmRegistryServer"); v != reg {
		t.Fatalf("new file: %q", v)
	}
	os.WriteFile(filepath.Join(dir, "list.yml"), []byte("- a\n"), 0o644)
	if err := yamlSet(filepath.Join(dir, "list.yml"), "x", false, "a"); err == nil {
		t.Fatal("a non-mapping file was overwritten")
	}
}

func TestNpmrcEditing(t *testing.T) {
	p := filepath.Join(t.TempDir(), ".npmrc")
	os.WriteFile(p, []byte("save-exact=true\n//deploy.example.com/npm/:_authToken=old\n@x:registry=https://r.example/\n//deploy.example.com/npm/:_authToken=dup\n"), 0o644)
	key := npmrcAuthKey("https://deploy.example.com/npm/")
	if key != "//deploy.example.com/npm/:_authToken" {
		t.Fatal(key)
	}
	if err := npmrcSet(p, key, "new"); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(p)
	if got := string(b); got != "save-exact=true\n//deploy.example.com/npm/:_authToken=new\n@x:registry=https://r.example/\n" {
		t.Fatalf("%q", got)
	}
	if npmrcGet(p, key) != "new" {
		t.Fatal("read back")
	}
	checkMode(t, p, 0o600)
}

