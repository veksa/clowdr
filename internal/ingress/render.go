// RenderMain renders nginx.conf.
func RenderMain(o Options) string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("worker_processes auto;\n")
	if o.WorkerShutdownTimeout > 0 {
		fmt.Fprintf(&b, "worker_shutdown_timeout %ds;\n", int(o.WorkerShutdownTimeout/time.Second))
	}
	b.WriteString("pid /var/run/nginx.pid;\n")
	if o.Syslog {
		fmt.Fprintf(&b, "error_log syslog:server=unix:%s,tag=nginx,nohostname warn;\n", LogSocket)
	} else {
		b.WriteString("error_log stderr warn;\n")
	}
	b.WriteString(`
events {
    worker_connections 1024;
}

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    sendfile on;
    tcp_nopush on;
    keepalive_timeout 65;
    server_tokens off;
    server_names_hash_bucket_size 128;

    # Docker's embedded DNS: upstream container names are re-resolved, so a missing
    # container never stops nginx from starting.
    resolver 127.0.0.11 valid=10s ipv6=off;

    map $http_upgrade $connection_upgrade {
        default upgrade;
        ''      '';
    }
    map $http_x_forwarded_proto $clowdr_forwarded_proto {
        default $http_x_forwarded_proto;
        ''      $scheme;
    }

`)
	var proxies []string
	for _, p := range o.TrustedProxies {
		if p == "cloudflare" {
			proxies = append(proxies, cloudflareIPs...)
		} else {
			proxies = append(proxies, p)
		}
	}
	for _, p := range proxies {
		fmt.Fprintf(&b, "    set_real_ip_from %s;\n", p)
	}
	if len(proxies) > 0 {
		if contains(o.TrustedProxies, "cloudflare") {
			b.WriteString("    real_ip_header CF-Connecting-IP;\n\n")
		} else {
			b.WriteString("    real_ip_header X-Forwarded-For;\n    real_ip_recursive on;\n\n")
		}
	}
	b.WriteString(`    log_format json_combined escape=json '{"time":"$time_iso8601","ip":"$remote_addr",'
        '"host":"$host","method":"$request_method","uri":"$request_uri","status":$status,'
        '"bytes":$body_bytes_sent,"rt":$request_time,"urt":"$upstream_response_time",'
        '"ref":"$http_referer","ua":"$http_user_agent","country":"$http_cf_ipcountry"}';
`)
	if o.Syslog {
		fmt.Fprintf(&b, "    access_log syslog:server=unix:%s,tag=access,nohostname json_combined;\n", LogSocket)
	} else {
		b.WriteString("    access_log /dev/stdout json_combined;\n")
	}
	if o.ClientMaxBody > 0 {
		fmt.Fprintf(&b, "    client_max_body_size %d;\n", o.ClientMaxBody)
	}
	b.WriteString(`
    # Unknown hosts are dropped.
    server {
        listen 80 default_server;
        server_name _;
`)
	acmeIndent(&b)
	b.WriteString("        location / {\n            return 444;\n        }\n    }\n")
	if o.DeployHost != "" {
		renderDeployHost(&b, o)
	}
	fmt.Fprintf(&b, "\n    include %s/*.conf;\n}\n", ProjectsDir)
	return b.String()
}

func acmeIndent(b *strings.Builder) {
	fmt.Fprintf(b, "        location ^~ %s {\n            proxy_pass http://unix:%s;\n        }\n", ACMEChallenge, APISocket)
}

// renderDeployHost serves the API and registry: no body limit, no request buffering, so
// `docker push` streams layers straight to clowdrd.
func renderDeployHost(b *strings.Builder, o Options) {
	d := o.DeployHost
	fmt.Fprintf(b, "\n    server {\n        listen 80;\n        server_name %s;\n", d)
	acmeIndent(b)
	if !o.hasCert(d) {
		b.WriteString("        location / {\n            return 503;\n        }\n    }\n")
		return
	}
	b.WriteString("        location / {\n            return 301 https://$host$request_uri;\n        }\n    }\n")
	fmt.Fprintf(b, "\n    server {\n        listen 443 ssl;\n        http2 on;\n        server_name %s;\n", d)
	fmt.Fprintf(b, "        ssl_certificate %s/%s/fullchain.pem;\n", CertDir, d)
	fmt.Fprintf(b, "        ssl_certificate_key %s/%s/privkey.pem;\n", CertDir, d)
	fmt.Fprintf(b, `        client_max_body_size 0;
        proxy_request_buffering off;
        proxy_buffering off;
        proxy_read_timeout 900s;
        proxy_send_timeout 900s;
        location / {
            proxy_pass http://unix:%s;
            proxy_http_version 1.1;
            proxy_set_header Host $host;
            proxy_set_header X-Forwarded-For $remote_addr;
            proxy_set_header X-Forwarded-Proto https;
        }
    }
`, APISocket)
}

// ProxyDefaultsConf is included by every generated location.
const ProxyDefaultsConf = generatedHeader + `proxy_http_version 1.1;
proxy_set_header Host $host;
proxy_set_header X-Real-IP $remote_addr;
proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
proxy_set_header X-Forwarded-Proto $clowdr_forwarded_proto;
proxy_set_header X-Forwarded-Host $host;
proxy_set_header Upgrade $http_upgrade;
proxy_set_header Connection $connection_upgrade;
`

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}
