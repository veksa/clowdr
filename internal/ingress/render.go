// Package ingress renders nginx configuration from clowdrd state and applies it with
// `nginx -t` + graceful reload, like ingress-nginx does in Kubernetes.
package ingress

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/veksa/clowdr/internal/logs"
	"github.com/veksa/clowdr/internal/spec"
)

// Paths are the same on the host and inside the nginx container (bind-mounted 1:1).
const (
	ConfDir         = "/etc/clowdr/nginx"
	ProjectsDir     = ConfDir + "/conf.d"
	MainConf        = ConfDir + "/nginx.conf"
	ProxyDefaults   = ConfDir + "/proxy_defaults.conf"
	CertDir         = "/var/lib/clowdr/certs"
	RunDir          = "/run/clowdr"
	APISocket       = RunDir + "/api.sock"
	LogSocket       = RunDir + "/log.sock"
	ACMEChallenge   = "/.well-known/acme-challenge/"
	generatedHeader = "# Generated by clowdrd. Do not edit: changes are overwritten on the next deploy.\n"
)

// Options are host-wide settings for rendering.
type Options struct {
	// Syslog sends access/error logs to clowdrd's syslog socket; false logs to stdout/stderr.
	Syslog bool
	// TrustedProxies are CIDRs (or "cloudflare") whose X-Forwarded/CF headers are trusted.
	TrustedProxies []string
	// WorkerShutdownTimeout bounds how long old workers keep long connections after reload.
	WorkerShutdownTimeout time.Duration
	// ClientMaxBody is the default client_max_body_size; 0 keeps nginx's default (1m).
	ClientMaxBody int64
	// DeployHost is deploy.<domain>, proxied to clowdrd's API socket. Empty = not served by nginx.
	DeployHost string
	// HasCert reports whether a certificate for domain exists in CertDir.
	HasCert func(domain string) bool
}

func (o Options) hasCert(d string) bool { return o.HasCert != nil && o.HasCert(d) }

// proxyOnly reports whether sites without `tls: direct` accept connections only from the
// trusted proxies (see RenderMain).
func (o Options) proxyOnly() bool { return len(o.TrustedProxies) > 0 }

// ServiceView is a service with the containers currently serving it.
type ServiceView struct {
	Spec    spec.Service
	Targets []string // host:port, empty when stopped
}

// UpstreamName is the nginx upstream for a service.
func UpstreamName(project, service string) string { return project + "__" + service }

// RenderProject renders conf.d/<project>.conf.
func RenderProject(project string, services []ServiceView, o Options) (string, error) {
	var b strings.Builder
	b.WriteString(generatedHeader)
	sort.Slice(services, func(i, j int) bool { return services[i].Spec.Name < services[j].Spec.Name })
	byName := map[string]*ServiceView{}
	for i := range services {
		byName[services[i].Spec.Name] = &services[i]
	}

	for _, s := range services {
		if s.Spec.Port == 0 {
			continue
		}
		up := UpstreamName(project, s.Spec.Name)
		fmt.Fprintf(&b, "\nupstream %s {\n    zone %s 64k;\n", up, up)
		if len(s.Targets) == 0 {
			b.WriteString("    server 127.0.0.1:1 down;\n")
		}
		for _, t := range s.Targets {
			fmt.Fprintf(&b, "    server %s resolve max_fails=1 fail_timeout=5s;\n", t)
		}
		b.WriteString("    keepalive 16;\n}\n")
	}

	for _, s := range services {
		if err := checkExtra(project, s.Spec.NginxExtra); err != nil {
			return "", fmt.Errorf("service %s: nginx_extra: %w", s.Spec.Name, err)
		}
		for _, r := range s.Spec.Routes {
			if err := checkExtra(project, r.NginxExtra); err != nil {
				return "", fmt.Errorf("service %s route %s: nginx_extra: %w", s.Spec.Name, r.Path, err)
			}
		}
		domains := append([]string(nil), s.Spec.Domains...)
		sort.Strings(domains)
		for _, d := range domains {
			renderServer(&b, project, s, d, byName, o)
		}
	}
	return b.String(), nil
}

func renderServer(b *strings.Builder, project string, s ServiceView, domain string, byName map[string]*ServiceView, o Options) {
	direct := s.Spec.TLS == spec.TLSDirect
	cert := direct && o.hasCert(domain)

	// Port 80. For tls: direct with a certificate it only answers ACME and redirects.
	fmt.Fprintf(b, "\nserver {\n    listen 80;\n    server_name %s;\n", domain)
	accessLog(b, project, o)
	if direct {
		acmeLocation(b)
	} else if o.proxyOnly() {
		b.WriteString("    if ($clowdr_via_proxy = 0) {\n        return 444;\n    }\n")
	}
	if cert {
		b.WriteString("    location / {\n        return 301 https://$host$request_uri;\n    }\n}\n")
	} else {
		serverBody(b, project, s, byName)
		b.WriteString("}\n")
	}

	if cert {
		fmt.Fprintf(b, "\nserver {\n    listen 443 ssl;\n    http2 on;\n    server_name %s;\n", domain)
		fmt.Fprintf(b, "    ssl_certificate %s/%s/fullchain.pem;\n", CertDir, domain)
		fmt.Fprintf(b, "    ssl_certificate_key %s/%s/privkey.pem;\n", CertDir, domain)
		accessLog(b, project, o)
		serverBody(b, project, s, byName)
		b.WriteString("}\n")
	}
}

func accessLog(b *strings.Builder, project string, o Options) {
	if o.Syslog {
		fmt.Fprintf(b, "    access_log syslog:server=unix:%s,tag=%s,nohostname json_combined;\n", LogSocket, logs.SyslogTag(project))
	}
}

func acmeLocation(b *strings.Builder) {
	fmt.Fprintf(b, "    location ^~ %s {\n        proxy_pass http://unix:%s;\n    }\n", ACMEChallenge, APISocket)
}

func serverBody(b *strings.Builder, project string, s ServiceView, byName map[string]*ServiceView) {
	if s.Spec.MaxBody != nil {
		fmt.Fprintf(b, "    client_max_body_size %d;\n", *s.Spec.MaxBody)
	}
	if s.Spec.Timeout > 0 {
		writeTimeout(b, "    ", s.Spec.Timeout)
	}
	if s.Spec.NginxExtra != "" {
		writeExtra(b, "    ", s.Spec.NginxExtra)
	}
	hasRoot := false
	for _, r := range s.Spec.Routes {
		if r.Path == "/" {
			hasRoot = true
		}
		target := s.Spec.Name
		if r.Service != "" {
			target = r.Service
		}
		writeLocation(b, project, r, target, byName)
	}
	if !hasRoot {
		writeLocation(b, project, spec.Route{Path: "/"}, s.Spec.Name, byName)
	}
}

func writeLocation(b *strings.Builder, project string, r spec.Route, target string, byName map[string]*ServiceView) {
	fmt.Fprintf(b, "    location %s {\n", r.Path)
	t, ok := byName[target]
	if !ok || t.Spec.Port == 0 {
		b.WriteString("        return 503;\n    }\n")
		return
	}
	fmt.Fprintf(b, "        proxy_pass http://%s;\n", UpstreamName(project, target))
	fmt.Fprintf(b, "        include %s;\n", ProxyDefaults)
	if r.Timeout > 0 {
		writeTimeout(b, "        ", r.Timeout)
	}
	if r.Buffering != nil && !*r.Buffering {
		b.WriteString("        proxy_buffering off;\n        proxy_request_buffering off;\n")
	}
	if r.MaxBody != nil {
		fmt.Fprintf(b, "        client_max_body_size %d;\n", *r.MaxBody)
	}
	if r.NginxExtra != "" {
		writeExtra(b, "        ", r.NginxExtra)
	}
	b.WriteString("    }\n")
}

func writeTimeout(b *strings.Builder, indent string, d time.Duration) {
	s := strconv.FormatInt(int64(d/time.Second), 10) + "s"
	fmt.Fprintf(b, "%sproxy_read_timeout %s;\n%sproxy_send_timeout %s;\n", indent, s, indent, s)
}

func writeExtra(b *strings.Builder, indent, extra string) {
	for _, line := range strings.Split(strings.TrimRight(extra, "\n"), "\n") {
		b.WriteString(indent + strings.TrimSpace(line) + "\n")
	}
}

// checkExtra keeps a raw snippet inside the block it is placed in and limited to directives
// that only shape this project's own traffic. Snippets are tokenized the way nginx reads them,
// and only allowed directives pass: a denylist missed `{alias ...}` and quoted directive names,
// and nginx can read every certificate key on the host. proxy_pass may only point at the
// project's own upstreams: nginx sits in every project network.
func checkExtra(project, s string) error {
	toks, err := extraTokens(s)
	if err != nil {
		return err
	}
	depth := 0
	var stmt []string
	for _, t := range toks {
		switch {
		case t.punct && t.v != "}":
			if len(stmt) == 0 {
				return fmt.Errorf("unexpected %q", t.v)
			}
			if err := checkDirective(project, stmt, t.v == "{"); err != nil {
				return err
			}
			if t.v == "{" {
				depth++
			}
			stmt = nil
		case t.punct:
			if len(stmt) > 0 {
				return fmt.Errorf("missing ';' after %s", stmt[0])
			}
			depth--
			if depth < 0 {
				return fmt.Errorf("unbalanced '}'")
			}
		default:
			stmt = append(stmt, t.v)
		}
	}
	if depth != 0 {
		return fmt.Errorf("unbalanced braces")
	}
	if len(stmt) > 0 {
		return fmt.Errorf("missing ';' after %s", stmt[0])
	}
	return nil
}

// extraTok is a word of a snippet (quotes removed) or one of the punctuation { } ;.
type extraTok struct {
	v     string
	punct bool
}

// extraTokens splits a snippet the way nginx's config parser does.
func extraTokens(s string) ([]extraTok, error) {
	var out []extraTok
	for i := 0; i < len(s); {
		c := s[i]
		switch {
		case c == ' ' || c == '\t' || c == '\n' || c == '\r':
			i++
		case c == '#':
			for i < len(s) && s[i] != '\n' {
				i++
			}
		case c == '{' || c == '}' || c == ';':
			out = append(out, extraTok{string(c), true})
			i++
		case c == '"' || c == '\'':
			var w strings.Builder
			j := i + 1
			for ; j < len(s) && s[j] != c; j++ {
				// nginx unescapes only some \x pairs: refused rather than guessed.
				if s[j] == '\\' {
					return nil, fmt.Errorf("no backslashes in quoted words")
				}
				w.WriteByte(s[j])
			}
			if j >= len(s) {
				return nil, fmt.Errorf("unbalanced quotes")
			}
			// nginx wants whitespace, ';' or '{' after a quoted word.
			if j+1 < len(s) && !strings.ContainsRune(" \t\r\n;{", rune(s[j+1])) {
				return nil, fmt.Errorf("unexpected %q after a quoted word", s[j+1])
			}
			out = append(out, extraTok{v: w.String()})
			i = j + 1
		default:
			// As in nginx, a bare word ends only at whitespace, ';' or '{': '#', '}', quotes and
			// '\' inside it are part of the word ("a#;" is the word "a#", not a comment). Words
			// holding any of them, or ${, are refused rather than read one way here and another
			// way by nginx.
			j := i
			for ; j < len(s) && !strings.ContainsRune(" \t\r\n;{", rune(s[j])); j++ {
			}
			w := s[i:j]
			if strings.ContainsAny(w, "#}\"'\\") || strings.HasSuffix(w, "$") && j < len(s) && s[j] == '{' {
				return nil, fmt.Errorf("%q: quote words with # } \\ or quotes in them, and use $var, not ${var}", w)
			}
			out = append(out, extraTok{v: w})
			i = j
		}
	}
	return out, nil
}

var (
	extraDirectives = map[string]bool{
		"add_header": true, "add_trailer": true, "expires": true, "etag": true, "charset": true, "default_type": true,
		"gzip": true, "gzip_types": true, "gzip_min_length": true, "gzip_comp_level": true, "gzip_vary": true, "gzip_proxied": true,
		"proxy_pass": true, "proxy_set_header": true, "proxy_hide_header": true, "proxy_pass_header": true, "proxy_ignore_headers": true,
		"proxy_read_timeout": true, "proxy_send_timeout": true, "proxy_connect_timeout": true,
		"proxy_buffering": true, "proxy_request_buffering": true, "proxy_buffer_size": true, "proxy_buffers": true,
		"proxy_busy_buffers_size": true, "proxy_max_temp_file_size": true, "proxy_http_version": true, "proxy_redirect": true,
		"proxy_cookie_path": true, "proxy_cookie_domain": true, "proxy_cookie_flags": true, "proxy_intercept_errors": true,
		"proxy_next_upstream": true, "proxy_next_upstream_tries": true, "proxy_next_upstream_timeout": true,
		"client_max_body_size": true, "client_body_buffer_size": true, "client_body_timeout": true,
		"send_timeout": true, "keepalive_timeout": true, "chunked_transfer_encoding": true,
		"return": true, "rewrite": true, "break": true, "set": true, "error_page": true, "internal": true,
		"allow": true, "deny": true, "sub_filter": true, "sub_filter_once": true, "sub_filter_types": true,
	}
	extraBlocks = map[string]bool{"location": true, "if": true, "limit_except": true}
)

func checkDirective(project string, stmt []string, block bool) error {
	name := stmt[0]
	if block != extraBlocks[name] || !block && !extraDirectives[name] {
		return fmt.Errorf("directive %q is not allowed in nginx_extra", name)
	}
	if name == "proxy_pass" {
		if len(stmt) != 2 || !ownUpstream(project, stmt[1]) {
			return fmt.Errorf("proxy_pass may only point at this project's services (http://%s)", UpstreamName(project, "<service>"))
		}
	}
	return nil
}

func ownUpstream(project, target string) bool {
	rest, ok := strings.CutPrefix(target, "http://"+UpstreamName(project, ""))
	if !ok {
		return false
	}
	svc, path, _ := strings.Cut(rest, "/")
	return spec.ValidName(svc) && !strings.Contains(path, "$")
}

